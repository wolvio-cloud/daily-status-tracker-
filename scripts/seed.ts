// Seed D1 with SAMPLE data (fake amounts) for local dev and demos.
//
//   pnpm seed                    # local D1, keeps existing rows
//   pnpm seed --reset            # local D1, wipes ALL tables first
//   pnpm seed --date 2026-09-30  # anchor dates to a fixed "today"
//   pnpm seed --remote --reset --i-understand-this-is-remote
//
// Writes the SQL to .wrangler/seed.sql, then runs `wrangler d1 execute`.
import { execFileSync } from 'node:child_process';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseArgs } from 'node:util';
import {
  ENTITY_NAMES,
  buildSampleData,
  datasetToSql,
  isIsoDate,
  todayIst,
} from '../packages/core/src/index';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

const { values } = parseArgs({
  options: {
    remote: { type: 'boolean', default: false },
    reset: { type: 'boolean', default: false },
    date: { type: 'string' },
    'i-understand-this-is-remote': { type: 'boolean', default: false },
    database: { type: 'string', default: 'founder-cockpit' },
  },
});

const today = values.date ?? todayIst();
if (!isIsoDate(today)) throw new Error(`--date must be YYYY-MM-DD, got ${today}`);
if (values.remote && !values['i-understand-this-is-remote']) {
  throw new Error('Refusing to seed the REMOTE database without --i-understand-this-is-remote');
}

const statements: string[] = ['-- SAMPLE DATA: fake amounts, generated by scripts/seed.ts'];
if (values.reset) {
  // Children before parents so foreign keys never block the delete.
  for (const t of ['confirm_tokens', 'audit_log', ...[...ENTITY_NAMES].reverse()]) {
    statements.push(`DELETE FROM ${t};`);
  }
}
const data = buildSampleData(today);
statements.push(...datasetToSql(data));

const outFile = join(root, '.wrangler', 'seed.sql');
mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, statements.join('\n') + '\n');

const counts = ENTITY_NAMES.map((e) => `${e}=${data[e].length}`).join(' ');
console.warn(`Seeding ${values.remote ? 'REMOTE' : 'local'} D1 (today=${today}): ${counts}`);

execFileSync(
  'pnpm',
  [
    '--filter',
    '@cockpit/mcp',
    'exec',
    'wrangler',
    'd1',
    'execute',
    values.database,
    values.remote ? '--remote' : '--local',
    '--file',
    outFile,
  ],
  { stdio: 'inherit', cwd: root },
);
